import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const timers=new Map(),listeners={};let next=0;
const panel={dataset:{},style:{}},canvas={getContext:()=>({})};
const c=vm.createContext({console,URLSearchParams,URL,Blob,ArrayBuffer,navigator:{},location:{search:''},document:{getElementById:n=>n==='display'?canvas:panel},Worker:function(){},setTimeout:(f,ms)=>{timers.set(++next,{f,ms});return next},clearTimeout:id=>timers.delete(id),addEventListener:(n,f)=>listeners[n]=f});
const run=s=>vm.runInContext(s,c);
for(const file of ['core.js','radar.js','background.js'])run(fs.readFileSync(file,'utf8'));
run('state.terminated=0;rdrDecode.worker={postMessage:()=>{},terminate:()=>state.terminated++};');
const a=run('rdrDecodeInWorker(new ArrayBuffer(2),"a","radar")').catch(e=>String(e));
const b=run('rdrDecodeInWorker(new ArrayBuffer(2),"b","radar")').catch(e=>String(e));
assert.equal(run('rdrDecode.jobs.length'),1,'one active decoder, second job queued');
assert.equal([...timers.values()][0].ms,30000,'active decode has bounded lifetime');
[...timers.values()][0].f();assert.match(await a,/timeout/);assert.match(await b,/timeout/);
assert.equal(run('state.terminated'),1);assert.equal(run('rdrDecode.active'),null);assert.equal(run('rdrDecode.jobs.length'),0);assert.equal(timers.size,0,'timeouts cleared on failure');
assert.match(await run('rdrDecodeInWorker(new ArrayBuffer(2),"c","radar")').catch(e=>String(e)),/fallback/,'worker failure backoff');
run('rdrDecode.retryAt=0;rdrDecode.worker={postMessage:()=>{},terminate:()=>state.terminated++};');
const pending=[];for(let i=0;i<5;i++)pending.push(run(`rdrDecodeInWorker(new ArrayBuffer(2),"q${i}","radar")`).catch(e=>String(e)));
assert.equal(run('rdrDecode.jobs.length'),3,'queue capped at three waiting jobs');assert.match(await pending[4],/queue full/);
listeners.pagehide();await Promise.all(pending);assert.equal(timers.size,0);assert.equal(run('rdrDecode.stopped'),true);
console.log('decoder timeout, queue cap, failure backoff and shutdown gates passed');
